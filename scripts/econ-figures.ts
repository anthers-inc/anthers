if (!existsSync(VAULT)) {
	console.log("  (vault not present — skipping wiki blocks)");
} else {
	const byFile = new Map<string, string>();
	for (const b of BLOCKS) {
		const path = join(VAULT, b.file);
		if (!existsSync(path)) {
			console.warn(`  ! missing ${b.file}`);
			continue;
		}
		const current = byFile.get(path) ?? (await readFile(path, "utf8"));
		const next = splice(current, b.key, b.render());
		if (next === null) {
			console.warn(`  ! no <!-- econ:begin ${b.key} --> markers in ${b.file}`);
			continue;
		}
		byFile.set(path, next);
	}
	for (const [path, next] of byFile) {
		await reconcile(path, next, path.slice(VAULT.length + 1));
	}
}

if (check && failures.length > 0) {
	console.error("\necon-figures --check FAILED. These are stale:\n");
	for (const f of failures) console.error(`  ${f}`);
	console.error("\nRun `bun run econ:figures` and commit the result.");
	process.exit(1);
}
console.log(check ? "econ-figures: up to date" : "econ-figures: done");
